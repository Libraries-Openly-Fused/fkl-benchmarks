// E1 (c): the batched DNN pre-processing pipeline of the paper (the workload of E4a, test_batchresize_x_split3D) written by hand,
// against FKL.
//
// BATCH crops of 60 x 120 pixels (8 bit, 3 channels), the crop i taken at (i, i) of a 3840 x 2160 source, are resized to 64 x 128
// with bilinear interpolation, the channels reordered (RGB to BGR), multiplied by 0.3, minus (1, 4, 3.2), divided by (3.2, 0.6, 11.8)
// and written as planar float tensor: plane c of image i at [i][c][y][x] (the layout of fk::TensorSplit, the one the batched
// pre-processing of cvGPUSpeedup writes). One kernel for the whole batch.
//
// RESIZE SAMPLING: the library default (ASYMMETRIC, source position = x * scale, the cv::cuda::resize convention) on both sides, the
// hand-written kernel and the FKL pipeline; the OpenCV-CUDA baseline of the same experiment uses it too. The half pixel variant is
// only used where NPP is the baseline. The CSV header says so.
//
// Versions (all with 32 x 8 threads per block, the block FKL launches for a 64 x 128 output: checked at compile time):
//   hand_batch    one kernel, blockIdx.z = image; the crop pointers in a `const __grid_constant__` array (8 bytes per crop), the crop
//                 size and the resize factors compile-time / kernel arguments; the arithmetic in the order FKL uses
//   hand_generic  the same with what FKL carries per crop: pointer, width, height and pitch (24 bytes), the kernel reading the source
//                 size and pitch from that descriptor
//   hand_padded   hand_generic with its parameter block padded to the size of FKL's read IOp (the crop descriptors, the resize parameters
//                 and the rest FKL carries per crop): a DIAGNOSTIC that separates the size of the parameter block from the generated code
//   fkl           FKL: BatchRead of the crops -> Resize -> VectorReorder -> Mul -> Sub -> Div -> TensorSplit, thread fusion off (the default)
// Each side owns its buffers, filled from the same host bytes. The hand-written kernels read a cudaMallocPitch image, their crops are pointers
// into it (source + i * pitch + i * sizeof(uchar3)), and they write a cudaMalloc tensor with the strides of fk::Tensor (checked at run time).
// FKL reads its own fk::Ptr2D image, its crops are crop2D views of it, and it writes its own fk::Tensor.
// Every version is compared bit by bit with hand_batch before anything is timed.
//
// Timing (fklb::timePreparedLaunch, common/cuda_timing.h). The crop locations may change on every image, so each version builds its batch
// before every launch, outside the GPU interval, and the host time of building and releasing it is a column of its own (<version>_prep_*):
//   hand_batch: the array of crop pointers; hand_generic, hand_padded: the array of crop descriptors;
//   fkl: the crop views and the read built on them (with the resize, which holds the per-crop resize parameters).
// The GPU columns time one launch of the prepared arguments: CUDA events, 100 iterations after a warm-up, mean and min.
// <version>_total_mean_ms = GPU mean + preparation mean. What does not depend on the crops is set up once: the strides, resize factors and
// constants of the hand-written kernels, and FKL's reorder, arithmetic and write (to the output tensor, which does not move).
//
// The batch sizes come from E1_PP_BATCHES (generated header, set by CMake): default 10, 50, 100, 200, 300. Writes e1_preproc.csv.
