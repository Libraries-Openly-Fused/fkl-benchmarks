namespace {
constexpr int SRC_W = 3840, SRC_H = 2160;
constexpr int CROP_W = 60, CROP_H = 120;
constexpr int UP_W = 64, UP_H = 128;
constexpr float ALPHA = 0.3f;
constexpr float SUB_X = 1.f, SUB_Y = 4.f, SUB_Z = 3.2f;
constexpr float DIV_X = 3.2f, DIV_Y = 0.6f, DIV_Z = 11.8f;
constexpr int BATCHES[] = {E1_PP_BATCHES};
static_assert(fk::getDefaultBlockSize(UP_W, UP_H).x == 32 && fk::getDefaultBlockSize(UP_W, UP_H).y == 8,
              "the hand-written kernels are launched with the block FKL launches for an output image");

template <int BATCH>
struct CropPointers {
    const unsigned char* data[BATCH];
};

template <int BATCH>
struct CropDescriptors {
    struct Crop { const unsigned char* data; unsigned int width, height, pitch; };
    Crop crop[BATCH];
};

__device__ __forceinline__ float3 loadPixel(const unsigned char* base, const size_t pitch, const int x, const int y) {
    const uchar3 p = *reinterpret_cast<const uchar3*>(base + y * pitch + x * sizeof(uchar3));
    return make_float3(static_cast<float>(p.x), static_cast<float>(p.y), static_cast<float>(p.z));
}

// resize (bilinear, ASYMMETRIC: the arithmetic of fk::InterpolateComplete) -> reorder -> * alpha -> - sub -> / div -> planar write.
// srcW and srcH are the size of the crop, imageStride the bytes between two images of the tensor, channelPixels the number of
// elements between two planes of an image (width * height), as fk::TensorSplit computes them.
__device__ __forceinline__ void preprocess(const unsigned char* base, const size_t inPitch, const int srcW, const int srcH, const float fx, const float fy,
                                           const int x, const int y, const int z, float* tensor, const size_t pitch, const size_t imageStride,
                                           const int channelPixels) {
    const float src_x = x * fx;
    const float src_y = y * fy;
    const int x1 = __float2int_rd(src_x);
    const int y1 = __float2int_rd(src_y);
    const int x2 = x1 + 1;
    const int y2 = y1 + 1;
    const int x2_read = min(x2, srcW - 1);
    const int y2_read = min(y2, srcH - 1);
    const float3 r00 = loadPixel(base, inPitch, x1, y1);
    const float3 r10 = loadPixel(base, inPitch, x2_read, y1);
    const float3 r01 = loadPixel(base, inPitch, x1, y2_read);
    const float3 r11 = loadPixel(base, inPitch, x2_read, y2_read);
    const float3 v = make_float3(
        (r00.x * ((x2 - src_x) * (y2 - src_y))) + (r10.x * ((src_x - x1) * (y2 - src_y))) + (r01.x * ((x2 - src_x) * (src_y - y1))) + (r11.x * ((src_x - x1) * (src_y - y1))),
        (r00.y * ((x2 - src_x) * (y2 - src_y))) + (r10.y * ((src_x - x1) * (y2 - src_y))) + (r01.y * ((x2 - src_x) * (src_y - y1))) + (r11.y * ((src_x - x1) * (src_y - y1))),
        (r00.z * ((x2 - src_x) * (y2 - src_y))) + (r10.z * ((src_x - x1) * (y2 - src_y))) + (r01.z * ((x2 - src_x) * (src_y - y1))) + (r11.z * ((src_x - x1) * (src_y - y1))));
    // RGB to BGR, then the three operations, each on the three channels
    const float o0 = ((v.z * ALPHA) - SUB_X) / DIV_X;
    const float o1 = ((v.y * ALPHA) - SUB_Y) / DIV_Y;
    const float o2 = ((v.x * ALPHA) - SUB_Z) / DIV_Z;
    float* const plane = reinterpret_cast<float*>(reinterpret_cast<char*>(tensor) + z * imageStride + y * pitch) + x;
    plane[0] = o0;
    plane[channelPixels] = o1;
    plane[2 * channelPixels] = o2;
}

template <int BATCH>
__global__ void handPreproc(const __grid_constant__ CropPointers<BATCH> crops, const size_t inPitch, float* __restrict__ tensor, const size_t pitch,
                            const size_t imageStride, const float fx, const float fy) {
    const int x = blockIdx.x * blockDim.x + threadIdx.x;
    const int y = blockIdx.y * blockDim.y + threadIdx.y;
    const int z = blockIdx.z;
    if (x >= UP_W || y >= UP_H) return;
    preprocess(crops.data[z], inPitch, CROP_W, CROP_H, fx, fy, x, y, z, tensor, pitch, imageStride, UP_W * UP_H);
}

template <int BATCH, size_t PAD>
struct PaddedCropDescriptors {
    CropDescriptors<BATCH> descriptors;
    unsigned char padding[PAD];
};

template <int BATCH, size_t PAD>
__global__ void handPreprocPadded(const __grid_constant__ PaddedCropDescriptors<BATCH, PAD> params, float* __restrict__ tensor, const size_t pitch,
                                  const size_t imageStride, const float fx, const float fy) {
    const int x = blockIdx.x * blockDim.x + threadIdx.x;
    const int y = blockIdx.y * blockDim.y + threadIdx.y;
    const int z = blockIdx.z;
    if (x >= UP_W || y >= UP_H) return;
    const auto& c = params.descriptors.crop[z];
    preprocess(c.data, c.pitch, static_cast<int>(c.width), static_cast<int>(c.height), fx, fy, x, y, z, tensor, pitch, imageStride, UP_W * UP_H);
}

template <int BATCH>
__global__ void handPreprocGeneric(const __grid_constant__ CropDescriptors<BATCH> crops, float* __restrict__ tensor, const size_t pitch,
                                   const size_t imageStride, const float fx, const float fy) {
    const int x = blockIdx.x * blockDim.x + threadIdx.x;
    const int y = blockIdx.y * blockDim.y + threadIdx.y;
    const int z = blockIdx.z;
    if (x >= UP_W || y >= UP_H) return;
    const auto& c = crops.crop[z];
    preprocess(c.data, c.pitch, static_cast<int>(c.width), static_cast<int>(c.height), fx, fy, x, y, z, tensor, pitch, imageStride, UP_W * UP_H);
}

template <int BATCH>
bool runPoint(cudaStream_t cs, fk::Stream_<fk::ParArch::GPU_NVIDIA>& fkStream, fklb::CsvWriter& csv, const std::vector<unsigned char>& noise) {
    // the hand-written kernels' source and tensor; the tensor is dense and planar, as fk::TensorSplit writes it
    unsigned char* hSrc = nullptr;
    size_t hPitch = 0;
    FKLB_CUDA_CHECK(cudaMallocPitch(reinterpret_cast<void**>(&hSrc), &hPitch, SRC_W * sizeof(uchar3), SRC_H));
    FKLB_CUDA_CHECK(cudaMemcpy2D(hSrc, hPitch, noise.data(), SRC_W * sizeof(uchar3), SRC_W * sizeof(uchar3), SRC_H, cudaMemcpyHostToDevice));
    const size_t pitch = UP_W * sizeof(float), imageStride = pitch * UP_H * 3, tensorBytes = imageStride * BATCH;
    float* hTensor = nullptr;
    FKLB_CUDA_CHECK(cudaMalloc(reinterpret_cast<void**>(&hTensor), tensorBytes));
    // FKL's source and tensor
    fk::Ptr2D<uchar3> dInput(SRC_W, SRC_H);
    FKLB_CUDA_CHECK(cudaMemcpy2D(dInput.ptr().data, dInput.ptr().dims.pitch, noise.data(), SRC_W * sizeof(uchar3), SRC_W * sizeof(uchar3), SRC_H,
                                 cudaMemcpyHostToDevice));
    fk::Tensor<float> dTensor(UP_W, UP_H, BATCH, 3);
    if (dTensor.ptr().dims.pitch != pitch || static_cast<size_t>(dTensor.ptr().dims.plane_pitch) * dTensor.ptr().dims.color_planes != imageStride ||
        dTensor.sizeInBytes() != tensorBytes) {
        throw std::runtime_error("the strides of fk::Tensor are not those of the hand-written kernels' tensor");
    }

    // the resize factors exactly as fk::Resize::build computes them
    const double cfx = static_cast<double>(UP_W) / CROP_W, cfy = static_cast<double>(UP_H) / CROP_H;
    const float fx = static_cast<float>(1.0 / cfx), fy = static_cast<float>(1.0 / cfy);

    // FKL's operations that do not depend on the crops, set up once like the constants of the hand-written kernels
    const auto reorder = fk::VectorReorder<float3, 2, 1, 0>::build();
    const auto mul = fk::Mul<float3>::build(make_float3(ALPHA, ALPHA, ALPHA));
    const auto sub = fk::Sub<float3>::build(make_float3(SUB_X, SUB_Y, SUB_Z));
    const auto div = fk::Div<float3>::build(make_float3(DIV_X, DIV_Y, DIV_Z));
    const auto write = fk::TensorSplit<float3>::build(dTensor.ptr());

    // The crop locations may change on every image: each version builds its batch for every launch (its preparation).
    const auto prepareHand = [&] {
        CropPointers<BATCH> crops;
        for (int i = 0; i < BATCH; ++i) crops.data[i] = hSrc + i * hPitch + i * sizeof(uchar3);
        return crops;
    };
    const auto prepareHandGeneric = [&] {
        CropDescriptors<BATCH> crops;
        for (int i = 0; i < BATCH; ++i) {
            crops.crop[i] = {hSrc + i * hPitch + i * sizeof(uchar3), static_cast<unsigned int>(CROP_W), static_cast<unsigned int>(CROP_H),
                             static_cast<unsigned int>(hPitch)};
        }
        return crops;
    };
    const auto prepareFkl = [&] {
        std::array<fk::Ptr2D<uchar3>, BATCH> crops;
        for (int i = 0; i < BATCH; ++i) crops[i] = dInput.crop2D(fk::Rect(i, i, CROP_W, CROP_H));
        return fk::PerThreadRead<fk::ND::_2D, uchar3>::build(crops).then(fk::Resize<fk::InterpolationType::INTER_LINEAR>::build(fk::Size(UP_W, UP_H)));
    };
    // the padding makes the hand-written parameter block as large as FKL's read IOp (which holds the per-crop pointers, sizes and resize parameters)
    constexpr size_t PAD = 24 * BATCH + 16;
    static_assert(sizeof(CropDescriptors<BATCH>) + PAD == sizeof(decltype(prepareFkl())), "hand_padded's parameter block is as large as FKL's read IOp");
    const auto prepareHandPadded = [&] {
        PaddedCropDescriptors<BATCH, PAD> params;
        for (int i = 0; i < BATCH; ++i) {
            params.descriptors.crop[i] = {hSrc + i * hPitch + i * sizeof(uchar3), static_cast<unsigned int>(CROP_W), static_cast<unsigned int>(CROP_H),
                                          static_cast<unsigned int>(hPitch)};
        }
        return params;
    };

    const dim3 block(32, 8);
    const dim3 grid((UP_W + block.x - 1) / block.x, (UP_H + block.y - 1) / block.y, BATCH);
    const auto launchHand = [&](const CropPointers<BATCH>& crops) {
        handPreproc<BATCH><<<grid, block, 0, cs>>>(crops, hPitch, hTensor, pitch, imageStride, fx, fy);
    };
    const auto launchHandGeneric = [&](const CropDescriptors<BATCH>& crops) {
        handPreprocGeneric<BATCH><<<grid, block, 0, cs>>>(crops, hTensor, pitch, imageStride, fx, fy);
    };
    const auto launchHandPadded = [&](const PaddedCropDescriptors<BATCH, PAD>& params) {
        handPreprocPadded<BATCH, PAD><<<grid, block, 0, cs>>>(params, hTensor, pitch, imageStride, fx, fy);
    };
    const auto launchFkl = [&](const auto& read) {
        fk::executeOperations<fk::TransformDPP<fk::ParArch::GPU_NVIDIA, fk::TF::DISABLED>>(fkStream, read, reorder, mul, sub, div, write);
    };

    // results first (bit-exact against hand_batch), then times
    std::vector<float> refHand(tensorBytes / sizeof(float)), outHandGeneric(refHand.size()), outHandPadded(refHand.size()), outFkl(refHand.size());
    FKLB_CUDA_CHECK(cudaMemset(hTensor, 0, tensorBytes));
    launchHand(prepareHand());
    FKLB_CUDA_CHECK(cudaGetLastError());
    FKLB_CUDA_CHECK(cudaStreamSynchronize(cs));
    FKLB_CUDA_CHECK(cudaMemcpy(refHand.data(), hTensor, tensorBytes, cudaMemcpyDeviceToHost));
    FKLB_CUDA_CHECK(cudaMemset(hTensor, 0, tensorBytes));
    launchHandGeneric(prepareHandGeneric());
    FKLB_CUDA_CHECK(cudaGetLastError());
    FKLB_CUDA_CHECK(cudaStreamSynchronize(cs));
    FKLB_CUDA_CHECK(cudaMemcpy(outHandGeneric.data(), hTensor, tensorBytes, cudaMemcpyDeviceToHost));
    FKLB_CUDA_CHECK(cudaMemset(hTensor, 0, tensorBytes));
    launchHandPadded(prepareHandPadded());
    FKLB_CUDA_CHECK(cudaGetLastError());
    FKLB_CUDA_CHECK(cudaStreamSynchronize(cs));
    FKLB_CUDA_CHECK(cudaMemcpy(outHandPadded.data(), hTensor, tensorBytes, cudaMemcpyDeviceToHost));
    FKLB_CUDA_CHECK(cudaMemset(dTensor.ptr().data, 0, tensorBytes));
    launchFkl(prepareFkl());
    FKLB_CUDA_CHECK(cudaGetLastError());
    FKLB_CUDA_CHECK(cudaStreamSynchronize(cs));
    FKLB_CUDA_CHECK(cudaMemcpy(outFkl.data(), dTensor.ptr().data, tensorBytes, cudaMemcpyDeviceToHost));
    const bool exactHandPadded = e1::sameBits(refHand, outHandPadded), exactHandGeneric = e1::sameBits(refHand, outHandGeneric);
    const bool exactFkl = e1::sameBits(refHand, outFkl);
    if (!exactFkl) {
        size_t differing = 0; float maxDiff = 0;
        for (size_t i = 0; i < refHand.size(); ++i) if (refHand[i] != outFkl[i]) { ++differing; maxDiff = static_cast<float>(fklb::maxKeepNaN(maxDiff, std::abs(refHand[i] - outFkl[i]))); }
        std::cerr << BATCH << " crops: FKL differs from the hand-written kernel in " << differing << " of " << refHand.size() << " elements, max " << maxDiff << std::endl;
    }

    fklb::Timing tHand, pHand, tHandGeneric, pHandGeneric, tHandPadded, pHandPadded, tFkl, pFkl;
    if (!e1::profileMode()) {   // in profile mode every kernel is launched once, by the checks above, and nothing is timed
        e1::timeVariants({[&] { fklb::timePreparedLaunch(cs, prepareHand, launchHand, tHand, pHand); },
                          [&] { fklb::timePreparedLaunch(cs, prepareHandGeneric, launchHandGeneric, tHandGeneric, pHandGeneric); },
                          [&] { fklb::timePreparedLaunch(cs, prepareHandPadded, launchHandPadded, tHandPadded, pHandPadded); },
                          [&] { fklb::timePreparedLaunch(cs, prepareFkl, launchFkl, tFkl, pFkl); }});
    }
    csv.row(BATCH, tHand.mean, tHand.min, tHandGeneric.mean, tHandGeneric.min, tFkl.mean, tFkl.min, tFkl.mean / tHand.mean,
            tFkl.mean / tHandGeneric.mean, int(exactFkl), int(exactHandGeneric), sizeof(CropPointers<BATCH>), sizeof(CropDescriptors<BATCH>), tHandPadded.mean, tHandPadded.min,
            tFkl.mean / tHandPadded.mean, int(exactHandPadded), sizeof(decltype(prepareFkl())),
            pHand.mean, pHand.min, tHand.mean + pHand.mean, pHandGeneric.mean, pHandGeneric.min, tHandGeneric.mean + pHandGeneric.mean,
            pHandPadded.mean, pHandPadded.min, tHandPadded.mean + pHandPadded.mean, pFkl.mean, pFkl.min, tFkl.mean + pFkl.mean);
    csv.flush();
    std::cout << BATCH << " crops: hand " << tHand.mean << " ms, hand_generic " << tHandGeneric.mean << ", hand_padded " << tHandPadded.mean << ", fkl " << tFkl.mean
              << " | preparation: hand " << pHand.mean << " ms, hand_generic " << pHandGeneric.mean << ", hand_padded " << pHandPadded.mean << ", fkl " << pFkl.mean
              << " | bit-exact vs hand: hand_generic " << exactHandGeneric << ", hand_padded " << exactHandPadded << ", fkl " << exactFkl << std::endl;
    FKLB_CUDA_CHECK(cudaFree(hSrc));
    FKLB_CUDA_CHECK(cudaFree(hTensor));
    return exactFkl && exactHandGeneric && exactHandPadded;
}

template <size_t... Is>
bool runAll(std::index_sequence<Is...>, cudaStream_t cs, fk::Stream_<fk::ParArch::GPU_NVIDIA>& fkStream, fklb::CsvWriter& csv, const std::vector<unsigned char>& noise) {
    return (runPoint<BATCHES[Is]>(cs, fkStream, csv, noise) & ...);
}
}  // namespace

int launch() {
    cudaStream_t cs;
    FKLB_CUDA_CHECK(cudaStreamCreate(&cs));
    fk::Stream_<fk::ParArch::GPU_NVIDIA> fkStream(cs);

    std::mt19937_64 gen(20261030ull);
    std::uniform_int_distribution<int> dist(0, 255);
    std::vector<unsigned char> noise(static_cast<size_t>(SRC_W) * SRC_H * 3);
    for (auto& v : noise) v = static_cast<unsigned char>(dist(gen));

    fklb::CsvWriter csv("e1_preproc.csv", "E1c hand-written batched pre-processing vs FKL (60x120 uchar3 crops -> 64x128 float planar tensor)",
                        {"batch", "hand_mean_ms", "hand_min_ms", "hand_generic_mean_ms", "hand_generic_min_ms", "fkl_mean_ms", "fkl_min_ms",
                         "fkl_over_hand", "fkl_over_hand_generic", "fkl_bitexact", "hand_generic_bitexact",
                         "hand_param_bytes", "hand_generic_param_bytes", "hand_padded_mean_ms", "hand_padded_min_ms", "fkl_over_hand_padded", "hand_padded_bitexact",
                         "fkl_read_iop_bytes", "hand_prep_mean_ms", "hand_prep_min_ms", "hand_total_mean_ms", "hand_generic_prep_mean_ms",
                         "hand_generic_prep_min_ms", "hand_generic_total_mean_ms", "hand_padded_prep_mean_ms", "hand_padded_prep_min_ms",
                         "hand_padded_total_mean_ms", "fkl_prep_mean_ms", "fkl_prep_min_ms", "fkl_total_mean_ms"},
                        std::string("thread fusion: off (fk::TF::DISABLED, the default); resize sampling: ASYMMETRIC (x * scale), the library default, in the hand-written kernels and in FKL (fk::Resize<INTER_LINEAR>); "
                                    "source: seeded uint8 noise 3840x2160x3 (std::mt19937_64 seed 20261030), uploaded to each side's own image (hand-written "
                                    "kernels: cudaMallocPitch, crops are pointers into it; FKL: fk::Ptr2D, crops are crop2D views), crop i at (i, i), 60x120 -> "
                                    "64x128 bilinear, RGB to BGR, *0.3, -(1, 4, 3.2), /(3.2, 0.6, 11.8), planar float output; 32x8 threads per block (the block "
                                    "FKL launches for an output image); GPU columns: CUDA events around one launch of prepared arguments, 100 timed iterations "
                                    "after one warm-up; *_prep_*: host time (steady_clock) of building and releasing the batch of one launch (hand: the crop "
                                    "pointers; hand_generic and hand_padded: the crop descriptors; fkl: the crop views and the read with the resize), done "
                                    "before every launch because the crops may move, outside the GPU interval; *_total_mean_ms = GPU mean + preparation mean; "
                                    "*_bitexact = same bytes as hand_batch") +
                            (e1::profileMode() ? "; PROFILE MODE (E1_PROFILE=1): nothing was timed, the times are zero" : ""));
    return runAll(std::make_index_sequence<sizeof(BATCHES) / sizeof(BATCHES[0])>{}, cs, fkStream, csv, noise) ? 0 : -1;
}
