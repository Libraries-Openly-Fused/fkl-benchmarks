"""E3 generator: one translation unit per chain length N, with N distinct parameterised operations in one fused kernel.

  gen_chain.py <variant A|B|L> <N> <out.cu> [old|new]

Variant A (float): the operations cycle Mul, Add, Sub, Div, Max, Min on float, each with its own parameter value.
Variant B (float3 with type changes): the period is Mul<float3>, Add<float3>, VectorReorder<float3, 2, 1, 0>, Cast<float3, int3>, Add<int3>,
Cast<int3, float3>, Sub<float3>, Div<float3>; the parameterised ones have their own parameter value. A chain that ends on an int3
value gets one closing Cast<int3, float3> (N + 1 operations in that case; the result type is always float3).
Variant L (legacy, for the fold-versus-recursion comparison against older FKL trees): float, Mul and Add alternating with distinct parameters, written with
the API that both the old trees (headers .cuh, fk::executeOperations(cudaStream_t, ...), commit 1f33224) and the newer ones (headers .h,
fk::executeOperations<fk::TransformDPP<>>(fk::Stream, ...)) accept: the optional style argument selects 'old' or 'new' (default new).
Every parameterised operation adds its parameter to the kernel parameter block (the limit that stops the chains is checked by the
sweep, not here). The same source is compiled as CUDA (nvcc) and, with -DE3_CPU, as plain C++ for the CPU back-end (g++), where the
translation unit contains no device code. The program runs the chain once and prints the kernel time, so that the occupancy and the
time can be taken afterwards from the same binary (scripts/e3_sweep.py, E1-style ncu run).
"""
import sys

VARIANTS = {
    "A": dict(read="float", write="float", period=[
        ("fk::Mul<float>", True), ("fk::Add<float>", True), ("fk::Sub<float>", True),
        ("fk::Div<float>", True), ("fk::Max<float>", True), ("fk::Min<float>", True)]),
    "B": dict(read="fk::float3", write="fk::float3", period=[
        ("fk::Mul<fk::float3>", True), ("fk::Add<fk::float3>", True), ("fk::VectorReorder<fk::float3, 2, 1, 0>", False),
        ("fk::Cast<fk::float3, fk::int3>", False), ("fk::Add<fk::int3>", True), ("fk::Cast<fk::int3, fk::float3>", False),
        ("fk::Sub<fk::float3>", True), ("fk::Div<fk::float3>", True)]),
}


def param_literal(variant, op, i):
    v = 1.0 + 0.000123 * (i + 1)
    if "int3" in op and op.startswith("fk::Add"):
        return f"fk::make_<fk::int3>({i % 7 + 1}, {i % 5 + 1}, {i % 3 + 1})"
    if variant == "A":
        return f"{v:.6f}f"
    return f"fk::make_<fk::float3>({v:.6f}f, {v + 0.01:.6f}f, {v + 0.02:.6f}f)"


def legacy(n, out, style):
    ops = ",\n        ".join(f"fk::{'Mul' if i % 2 == 0 else 'Add'}<float>::build({1.0 + 0.000123 * (i + 1):.6f}f)" for i in range(n))
    if style == "old":
        head = ("#include <fused_kernel/fused_kernel.cuh>\n#include <fused_kernel/algorithms/basic_ops/arithmetic.cuh>\n"
                "#include <fused_kernel/core/data/ptr_nd.cuh>\n")
        decl = "    cudaStream_t stream;\n    cudaStreamCreate(&stream);\n"
        call = "fk::executeOperations(stream,"
    else:
        head = ("#include <fused_kernel/fused_kernel.h>\n#include <fused_kernel/algorithms/basic_ops/arithmetic.h>\n"
                "#include <fused_kernel/core/data/ptr_utils.h>\n#include <fused_kernel/core/execution_model/executors.h>\n")
        decl = "    fk::Stream stream;\n"
        call = "fk::executeOperations<fk::TransformDPP<>>(stream,"
    open(out, "w").write(f"""// generated by gen_chain.py: variant L ({style} API), N = {n}
{head}
int main() {{
    constexpr int W = 1920, H = 1080;
{decl}    fk::Ptr2D<float> in(W, H);
    fk::Ptr2D<float> out(W, H);
    {call} fk::PerThreadRead<fk::ND::_2D, float>::build(in),
        {ops},
        fk::PerThreadWrite<fk::ND::_2D, float>::build(out));
    return 0;
}}
""")


def main():
    variant, n, out = sys.argv[1], int(sys.argv[2]), sys.argv[3]
    if variant == "L":
        legacy(n, out, sys.argv[4] if len(sys.argv) > 4 else "new")
        return
    cfg = VARIANTS[variant]
    ops = []
    for i in range(n):
        op, has_param = cfg["period"][i % len(cfg["period"])]
        ops.append(f"{op}::build({param_literal(variant, op, i)})" if has_param else f"{op}::build()")
    if variant == "B" and n % 8 in (4, 5):    # the chain ends on an int3 value (after Cast<float3, int3> or Add<int3>): close it with the cast back
        ops.append("fk::Cast<fk::int3, fk::float3>::build()")
    rd, wr = cfg["read"], cfg["write"]
    body = ",\n            ".join(ops)
    src = f'''// generated by gen_chain.py: variant {variant}, N = {n}
#include <chrono>
#include <cstdio>

#include <fused_kernel/fused_kernel.h>
#include <fused_kernel/algorithms/basic_ops/arithmetic.h>
#include <fused_kernel/algorithms/basic_ops/cast.h>
#include <fused_kernel/algorithms/basic_ops/logical.h>
#include <fused_kernel/algorithms/basic_ops/vector_ops.h>
#include <fused_kernel/core/data/ptr_utils.h>
#include <fused_kernel/core/execution_model/executors.h>

int main() {{
#ifdef E3_CPU
    constexpr fk::ParArch PAR = fk::ParArch::CPU;
    constexpr int W = 64, H = 64;
    fk::Stream_<PAR> stream;
    fk::Ptr2D<{rd}> in(W, H, 0, fk::MemType::Host);
    fk::Ptr2D<{wr}> out(W, H, 0, fk::MemType::Host);
#else
    constexpr fk::ParArch PAR = fk::ParArch::GPU_NVIDIA;
    constexpr int W = 1920, H = 1080;
    fk::Stream_<PAR> stream;
    fk::Ptr2D<{rd}> in(W, H);
    fk::Ptr2D<{wr}> out(W, H);
    cudaMemset(in.ptr().data, 0, in.sizeInBytes());
#endif
    const auto read = fk::PerThreadRead<fk::ND::_2D, {rd}>::build(in);
    const auto write = fk::PerThreadWrite<fk::ND::_2D, {wr}>::build(out);
    auto run = [&]() {{
        fk::executeOperations<fk::TransformDPP<PAR>>(stream, read,
            {body},
            write);
    }};
    run();
    stream.sync();
    const auto t0 = std::chrono::steady_clock::now();
    for (int i = 0; i < 20; ++i) run();
    stream.sync();
    const auto t1 = std::chrono::steady_clock::now();
    std::printf("variant {variant} N {n}: %.6f ms per launch\\n", std::chrono::duration<double, std::milli>(t1 - t0).count() / 20);
    return 0;
}}
'''
    open(out, "w").write(src)


if __name__ == "__main__":
    main()
